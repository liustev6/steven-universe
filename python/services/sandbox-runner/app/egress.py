"""The egress proxy of one pod (sandbox-runner.md R12): its nginx config.

Each pod gets its own proxy, started from a stock nginx image (non-root) with this config,
mounted read-only. The config is the proxy's whole identity and policy:
- listen on the pod network only (port 8080; the sandbox reaches it by IP, R11);
- forward every request to the one upstream, the gateway, whatever URL or Host the sandbox sends;
- resolve the gateway's name per request (cached 30 s), not once at start: a proxy starts even while
  the gateway is unreachable (its requests get 502 until it's back), and follows an address change;
- stamp `X-Sandbox-Id` with this pod's sandbox, replacing any value the sandbox sent;
- stream both ways (no buffering): model replies arrive token by token;
- verify the gateway's TLS certificate when the upstream is https.
The sandbox can't change any of this: it only ever sees the proxy's port.
"""

from __future__ import annotations

import re
import uuid
from urllib.parse import urlsplit

LISTEN_PORT = 8080
CA_BUNDLE = "/etc/ssl/certs/ca-certificates.crt"   # in the nginx image
DOCKER_DNS = "127.0.0.11"                           # Docker's resolver, for a container on a user-defined network

_TEMPLATE = """\
# Generated by sandbox-runner for {sandbox_id}. Do not edit: the pod is destroyed with it.
worker_processes 1;
pid /tmp/nginx.pid;
error_log /dev/stderr warn;
events {{ worker_connections 256; }}

http {{
    access_log off;
    server_tokens off;
    client_body_temp_path /tmp/client_body;
    proxy_temp_path /tmp/proxy;
    fastcgi_temp_path /tmp/fastcgi;
    uwsgi_temp_path /tmp/uwsgi;
    scgi_temp_path /tmp/scgi;
    client_max_body_size 64m;
    resolver {resolver} valid=30s ipv6=off;
    resolver_timeout 5s;

    server {{
        listen {port};
        set $gateway {upstream};                # a variable: resolved per request, through the resolver
        location / {{
            proxy_pass $gateway;
            proxy_http_version 1.1;
            proxy_set_header Host {upstream_host};
            proxy_set_header Connection "";
            proxy_set_header X-Sandbox-Id "{sandbox_id}";
            proxy_set_header X-Forwarded-For "";
            proxy_buffering off;
            proxy_request_buffering off;
            proxy_read_timeout 600s;
            proxy_send_timeout 600s;
{tls}        }}
    }}
}}
"""

_TLS = """\
            proxy_ssl_server_name on;
            proxy_ssl_name {upstream_hostname};
            proxy_ssl_verify on;
            proxy_ssl_verify_depth 3;
            proxy_ssl_trusted_certificate {ca};
"""


def new_sandbox_id() -> uuid.UUID:
    """A sandbox's id: random, made by the runner, never taken from a request."""
    return uuid.uuid4()


def proxy_config(sandbox_id: uuid.UUID, upstream: str, resolver: str = DOCKER_DNS) -> str:
    """nginx.conf for one pod's proxy. `upstream`: the gateway's base URL, e.g. https://agent.lan.example:8443.

    The id is a UUID, not a string: its text is only hex digits and dashes, so it can't break out of
    the header's quotes, by construction rather than by a check.
    """
    if not isinstance(sandbox_id, uuid.UUID):
        raise TypeError(f"sandbox_id must be a uuid.UUID, got {type(sandbox_id).__name__}")
    u = urlsplit(upstream)
    if u.scheme not in ("http", "https") or not u.hostname or u.path not in ("", "/") or u.query or u.fragment \
            or u.username or u.password:
        raise ValueError(f"upstream must be a plain http(s)://host[:port] URL, got {upstream!r}")
    if not re.fullmatch(r"[A-Za-z0-9.-]+", u.hostname):
        raise ValueError(f"bad upstream host: {u.hostname!r}")
    host = u.netloc
    tls = _TLS.format(upstream_hostname=u.hostname, ca=CA_BUNDLE) if u.scheme == "https" else ""
    return _TEMPLATE.format(sandbox_id=str(sandbox_id), port=LISTEN_PORT, upstream=f"{u.scheme}://{host}",
                            upstream_host=host, tls=tls, resolver=resolver)
